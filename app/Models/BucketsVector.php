<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Relations\HasMany;

class BucketsVector extends Model
{
    use HasFactory;

    protected $table = 'storage_buckets_vectors';
    protected $primaryKey = 'id';
    public $incrementing = false;
    protected $keyType = 'string';
    public $timestamps = true;
    protected $fillable = ['id', 'type', 'created_at', 'updated_at'];
    protected function casts(): array
    {
        return array (
  'created_at' => 'datetime',
  'updated_at' => 'datetime',
);
    }

    public function vectorIndexByBucketId(): HasMany { return $this->hasMany(\App\Models\VectorIndex::class, 'bucket_id', 'id'); }
}
